export async function main(argv = process.argv) {
  const inputPath = option('--input', argv);
  const outputPath = option('--output', argv) ?? DEFAULT_OUTPUT;
  const pricingOutputPath = option('--pricing-output', argv) ?? DEFAULT_PRICING_OUTPUT;
  const catalog = JSON.parse(
    inputPath
      ? await readFile(inputPath, 'utf8')
      : await fetch(SOURCE_URL, { signal: AbortSignal.timeout(10_000) }).then((response) => {
          if (!response.ok) throw new Error(`models.dev returned HTTP ${response.status}`);
          return response.text();
        }),
  );

  const generated = {};
  const generatedProviders = {};
  const generatedModelProviderOverrides = {};
  const directory = {};
  for (const [sourceId, provider] of Object.entries(catalog)) {
    if (typeof provider.id !== 'string') {
      throw new Error(`models.dev provider ${sourceId} has an unsupported shape`);
    }
    directory[provider.id] = {
      ...(typeof provider.api === 'string' ? { api: provider.api } : {}),
    };
  }
  for (const [providerType, sourceId] of Object.entries(PROVIDERS)) {
    const provider = catalog[sourceId];
    if (!provider) {
      throw new Error(`models.dev provider ${sourceId} is missing`);
    }
    if (!provider.models || typeof provider.models !== 'object') {
      throw new Error(`models.dev provider ${sourceId} has no models object`);
    }
    if (
      typeof provider.id !== 'string' ||
      typeof provider.name !== 'string' ||
      typeof provider.doc !== 'string'
    ) {
      throw new Error(`models.dev provider ${sourceId} has an unsupported shape`);
    }
    generatedProviders[providerType] = {
      id: provider.id,
      name: provider.name,
      ...(typeof provider.api === 'string' ? { api: provider.api } : {}),
      doc: provider.doc,
    };
    generated[providerType] = Object.fromEntries(
      Object.entries(provider.models)
        .sort(([left], [right]) => left.localeCompare(right))
        .map(([id, model]) => [id, toMetadata(sourceId, id, provider, model)]),
    );
    generatedModelProviderOverrides[providerType] = Object.fromEntries(
      Object.entries(provider.models)
        .sort(([left], [right]) => left.localeCompare(right))
        .filter(([, model]) => model.provider !== undefined)
        .map(([id, model]) => [id, toModelProviderOverride(sourceId, id, model.provider)]),
    );
  }

  const providerTypeUnion = Object.keys(PROVIDERS).map(JSON.stringify).join(' | ');
  const lines = [
    '// Generated by scripts/sync-model-metadata.mjs from https://models.dev/api.json.',
    '// Do not edit by hand; put access-path-specific facts in model-metadata.ts.',
    "import type { ModelMetadata } from './model-metadata.js';",
    '',
    `export const GENERATED_MODELS_DEV_METADATA: Record<${providerTypeUnion}, Record<string, ModelMetadata>> = {`,
  ];
  for (const [provider, models] of Object.entries(generated)) {
    lines.push(`  ${JSON.stringify(provider)}: {`);
    for (const [id, metadata] of Object.entries(models)) {
      lines.push(`    ${JSON.stringify(id)}: ${JSON.stringify(metadata)},`);
    }
    lines.push('  },');
  }
  lines.push('};', '');
  lines.push(
    `export const GENERATED_MODELS_DEV_MODEL_PROVIDER_OVERRIDES: Record<${providerTypeUnion}, Record<string, { npm: string; api?: string }>> = {`,
  );
  for (const [provider, overrides] of Object.entries(generatedModelProviderOverrides)) {
    lines.push(`  ${JSON.stringify(provider)}: ${JSON.stringify(overrides)},`);
  }
  lines.push('};', '');
  lines.push(
    `export const GENERATED_MODELS_DEV_PROVIDER_FACTS: Record<${providerTypeUnion}, { id: string; name: string; api?: string; doc: string }> = {`,
  );
  for (const [provider, facts] of Object.entries(generatedProviders)) {
    lines.push(`  ${JSON.stringify(provider)}: ${JSON.stringify(facts)},`);
  }
  lines.push('};', '');
  lines.push('export const GENERATED_MODELS_DEV_DIRECTORY: Record<string, { api?: string }> = {');
  for (const [id, facts] of Object.entries(directory).sort(([left], [right]) =>
    left.localeCompare(right),
  )) {
    lines.push(`  ${JSON.stringify(id)}: ${JSON.stringify(facts)},`);
  }
  lines.push('};', '');
  await writeFile(outputPath, lines.join('\n'));

  // Pricing: flatten each provider's models.dev `cost` into a sorted
  // `GENERATED_PRICING` array of flat `PricingConfig` (base rates only, per
  // #2329 non-goals). Models without a `cost` are omitted; special tiers
  // (coding plan, context_over_200k, …) stay overrides, not generated.
  const pricingEntries = [];
  for (const [providerType, sourceId] of Object.entries(PROVIDERS)) {
    const provider = catalog[sourceId];
    if (!provider?.models) continue;
    for (const [modelId, model] of Object.entries(provider.models)) {
      // modelKey uses `providerType` (not the models.dev `sourceId`) so it
      // matches what the cost layer looks up: `${connection.providerType}:${model}`.
      // Without this, alias providers (gemini-cli→google, MiniMax→minimax,
      // moonshot→moonshotai-cn, kimi-coding-plan→kimi-for-coding) would
      // generate modelKeys the consumer never queries, making their built-in
      // price unresolvable (#2329).
      const pricing = toPricingConfig(providerType, modelId, model);
      if (pricing) pricingEntries.push(pricing);
    }
  }
  pricingEntries.sort((left, right) => left.modelKey.localeCompare(right.modelKey));
  const pricingLines = [
    '// Generated by scripts/sync-model-metadata.mjs from https://models.dev/api.json.',
    '// Do not edit by hand; put access-path-specific pricing in',
    '// packages/runtime/src/telemetry/builtin-pricing.ts (local supplement layer).',
    "import type { PricingConfig } from './model-pricing.js';",
    '',
    'export const GENERATED_PRICING: readonly PricingConfig[] = [',
  ];
  for (const entry of pricingEntries) {
    pricingLines.push(`  ${JSON.stringify(entry)},`);
  }
  pricingLines.push('];', '');
  await writeFile(pricingOutputPath, pricingLines.join('\n'));
}

function toModelProviderOverride(providerId, modelId, override) {
  if (
    !override ||
    typeof override !== 'object' ||
    typeof override.npm !== 'string' ||
    (override.api !== undefined && typeof override.api !== 'string')
  ) {
    throw new Error(
      `models.dev model ${providerId}/${modelId} has an unsupported provider override`,
    );
  }
  return {
    npm: override.npm,
    ...(override.api ? { api: override.api } : {}),
  };
}

export function toMetadata(providerId, modelId, provider, model) {
  if (
    typeof provider.doc !== 'string' ||
    typeof model?.name !== 'string' ||
    (model.modalities !== undefined && !Array.isArray(model.modalities?.input)) ||
    typeof model.limit?.context !== 'number' ||
    typeof model.limit?.output !== 'number' ||
    typeof model.reasoning !== 'boolean' ||
    typeof model.tool_call !== 'boolean'
  ) {
    throw new Error(`models.dev model ${providerId}/${modelId} has an unsupported shape`);
  }
  const reasoningOptions = model.reasoning_options ?? [];
  if (!Array.isArray(reasoningOptions)) {
    throw new Error(`models.dev model ${providerId}/${modelId} has an unsupported shape`);
  }
  let efforts;
  let toggle = false;
  for (const entry of reasoningOptions) {
    if (entry?.type === 'effort') {
      if (!Array.isArray(entry.values) || entry.values.some((value) => typeof value !== 'string')) {
        throw new Error(`models.dev model ${providerId}/${modelId} has an unsupported shape`);
      }
      efforts = entry.values;
    } else if (entry?.type === 'toggle') {
      toggle = true;
    } else if (entry?.type !== 'budget_tokens') {
      // budget_tokens is a known models.dev option type with no wire consumer
      // yet; any other unknown type fails loudly so a models.dev schema change
      // is a conscious decision, not silent drift.
      throw new Error(`models.dev model ${providerId}/${modelId} has an unsupported shape`);
    }
  }
  return {
    displayName: model.name,
    lifecycle: toLifecycle(model.status),
    docsUrl: provider.doc,
    contextWindow: model.limit?.context,
    maxOutputTokens: model.limit?.output,
    ...(typeof model.limit?.input === 'number' ? { maxInputTokens: model.limit.input } : {}),
    capabilities: {
      ...(model.modalities ? { vision: model.modalities.input.includes('image') } : {}),
      reasoning: model.reasoning === true,
      functionCalling: model.tool_call === true,
    },
    ...(typeof model.description === 'string' && model.description
      ? { description: model.description }
      : {}),
    ...(typeof model.knowledge === 'string' && model.knowledge
      ? { knowledgeCutoff: model.knowledge }
      : {}),
    ...(model.structured_output === true ? { structuredOutput: true } : {}),
    ...(model.modalities?.input?.includes('pdf') ? { pdfInput: true } : {}),
    ...(typeof model.last_updated === 'string' && model.last_updated
      ? { lastUpdated: model.last_updated }
      : {}),
    ...(efforts?.length || toggle
      ? {
          thinkingOptions: {
            ...(efforts?.length ? { efforts } : {}),
            ...(toggle ? { toggle: true } : {}),
          },
        }
      : {}),
    ...(model.modalities
      ? {
          modalities: {
            input: model.modalities.input.filter(
              (value) =>
                value === 'text' || value === 'image' || value === 'audio' || value === 'pdf',
            ),
            output: (Array.isArray(model.modalities.output) ? model.modalities.output : []).filter(
              (value) => value === 'text' || value === 'image' || value === 'audio',
            ),
          },
        }
      : {}),
  };
}

/**
 * Map models.dev `status` to a lifecycle, preserving 'beta'/'alpha' distinctly
 * instead of collapsing them into 'active' (#2329). Unknown values fall back to
 * 'active' so a new models.dev status never breaks the sync.
 */
export function toLifecycle(status) {
  if (status === 'deprecated' || status === 'beta' || status === 'alpha' || status === 'retired') {
    return status;
  }
  return 'active';
}

/**
 * Convert a models.dev `cost` entry to a flat `PricingConfig` (base rates only).
 * models.dev cost shape: `{ input: 3, output: 15, cache_read: 0.3, cache_write: 3.75 }`
 * — already USD per 1M tokens (flat numbers, no tier sub-objects for the base
 * rate). Special tiers (context_over_200k, coding plan, etc.) are intentionally
 * not mapped — the flat `PricingConfig` carries the base rate only, per #2329
 * non-goals.
 */
export function toPricingConfig(providerId, modelId, model) {
  const cost = model?.cost;
  if (!cost || typeof cost !== 'object') return null;
  const input = ratePer1M(cost.input);
  const output = ratePer1M(cost.output);
  // Skip models with no real base rate (input/output 0 or missing). models.dev
  // reports special tiers (coding plans, free tiers) as cost 0; those are
  // intentionally not generated — they belong in the local supplement / override
  // layer (#2329 non-goals).
  if (input === undefined || output === undefined || input === 0 || output === 0) return null;
  const cacheRead = ratePer1M(cost.cache_read);
  const cacheWrite = ratePer1M(cost.cache_write);
  return {
    modelKey: `${providerId}:${modelId}`,
    inputUsdPer1M: input,
    outputUsdPer1M: output,
    ...(cacheRead !== undefined ? { cacheReadUsdPer1M: cacheRead } : {}),
    ...(cacheWrite !== undefined ? { cacheWriteUsdPer1M: cacheWrite } : {}),
  };
}

/**
 * Read a per-1M USD rate from a models.dev cost field. models.dev expresses base
 * rates as a plain number (USD / 1M tokens); a tiered sub-object
 * `{ token, unit }` (used for context_over_200k etc.) is intentionally rejected
 * here so special tiers don't leak into the base rate (#2329 non-goals).
 */
function ratePer1M(value) {
  if (typeof value !== 'number' || !Number.isFinite(value) || value < 0) return undefined;
  return value;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}

function option(name, argv) {
  const index = argv.indexOf(name);
  if (index === -1) return undefined;
  const value = argv[index + 1];
  if (!value || value.startsWith('--')) throw new Error(`${name} requires a value`);
  return value;
}
